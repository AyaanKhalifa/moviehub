/**
 * Returns an array of posters for a given movie/show.
 * If the title is in CURATED_POSTERS, returns those.
 * Otherwise, combines the movie's primary poster with related fallback posters.
 */
export const getMoviePosters = (movie) => {
  if (!movie) return [];

  const titleKey = (movie.Title || '').toLowerCase().trim();

  // 1. Exact match
  if (CURATED_POSTERS[titleKey]) {
    return CURATED_POSTERS[titleKey];
  }

  // 2. Sequel check: prevent Part 1 from matching Part 2, and Part 2 from matching Part 1
  const sequelRegex = /\b(part|chapter|vol|volume|ii|iii|iv|v|vi|2|3|4|5|rises|way of water)\b/i;
  const queryHasSequel = sequelRegex.test(titleKey);

  // Sort keys by descending length
  const sortedKeys = Object.keys(CURATED_POSTERS).sort((a, b) => b.length - a.length);

  for (const k of sortedKeys) {
    const keyHasSequel = sequelRegex.test(k);
    if (queryHasSequel && !keyHasSequel) continue;
    if (!queryHasSequel && keyHasSequel) continue;

    if (titleKey.includes(k) || k.includes(titleKey)) {
      return CURATED_POSTERS[k];
    }
  }

  // Default: if movie has a valid poster, return only its single official poster
  if (movie.Poster && movie.Poster !== 'N/A') {
    return [
      { url: movie.Poster, label: 'Official Theatrical Poster' }
    ];
  }

  return [];
};

