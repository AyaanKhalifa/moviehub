/**
 * Get season metadata: official season poster and official season trailer
 */
export const getSeasonData = (seriesTitle, seasonNumber, defaultPoster = null) => {
  if (!seriesTitle) return { poster: defaultPoster, trailerId: null, year: null, tagline: null };

  const clean = seriesTitle.toLowerCase().trim();
  const matchedKey = Object.keys(SERIES_SEASONS_DATA).find(
    (k) => clean.includes(k) || k.includes(clean)
  );

  if (matchedKey && SERIES_SEASONS_DATA[matchedKey][seasonNumber]) {
    const data = SERIES_SEASONS_DATA[matchedKey][seasonNumber];
    return {
      poster: data.poster || defaultPoster,
      trailerId: data.trailerId || null,
      year: data.year || null,
      tagline: data.tagline || null
    };
  }

  return {
    poster: defaultPoster,
    trailerId: null,
    year: null,
    tagline: null
  };
};

/**
 * Returns available seasons with curated data for a title
 */
export const getAvailableCuratedSeasons = (seriesTitle) => {
  if (!seriesTitle) return [];
  const clean = seriesTitle.toLowerCase().trim();
  const matchedKey = Object.keys(SERIES_SEASONS_DATA).find(
    (k) => clean.includes(k) || k.includes(clean)
  );
  if (matchedKey) {
    return Object.keys(SERIES_SEASONS_DATA[matchedKey]).map(Number);
  }
  return [];
};
